"""
Z-Sentinel explanation engine.

Converts fraud-intelligence signals into clear,
human-readable explanations for analysts.
"""

from __future__ import annotations


def explain_transaction(
    transaction: dict,
    signals: dict,
    network_degree: int = 0,
    connected_accounts: list | None = None,
) -> list[str]:
    """
    Generate human-readable explanations for a transaction.

    Parameters
    ----------
    transaction:
        Original transaction data.

    signals:
        Risk signals generated by the risk engine.

    network_degree:
        Number of relationships in the transaction's network.

    connected_accounts:
        Accounts connected through shared infrastructure.

    Returns
    -------
    list[str]
        Human-readable risk explanations.
    """

    reasons: list[str] = []

    # --------------------------------------------------------
    # Transaction amount
    # --------------------------------------------------------

    amount = float(
        transaction.get(
            "amount",
            0,
        )
    )

    if amount >= 5000:
        reasons.append(
            "High transaction amount"
        )

    # --------------------------------------------------------
    # Machine-learning fraud probability
    # --------------------------------------------------------

    ml_probability = float(
        signals.get(
            "ml_probability",
            0,
        )
    )

    if ml_probability >= 0.70:
        reasons.append(
            "High ML fraud probability"
        )

    elif ml_probability >= 0.50:
        reasons.append(
            "Elevated ML fraud probability"
        )

    # --------------------------------------------------------
    # Behavioral anomaly
    # --------------------------------------------------------

    anomaly_score = float(
        signals.get(
            "anomaly_score",
            0,
        )
    )

    if anomaly_score >= 0.70:
        reasons.append(
            "Highly unusual behavioral pattern"
        )

    elif anomaly_score >= 0.50:
        reasons.append(
            "Unusual behavioral pattern"
        )

    # --------------------------------------------------------
    # Transaction velocity
    # --------------------------------------------------------

    velocity_score = float(
        signals.get(
            "velocity_score",
            0,
        )
    )

    if velocity_score >= 0.75:
        reasons.append(
            "Very high transaction velocity"
        )

    elif velocity_score >= 0.50:
        reasons.append(
            "High transaction velocity"
        )

    # --------------------------------------------------------
    # Failed authentication attempts
    # --------------------------------------------------------

    failed_attempts = int(
        transaction.get(
            "failed_attempts",
            0,
        )
    )

    if failed_attempts >= 3:
        reasons.append(
            "Multiple recent failed attempts"
        )

    # --------------------------------------------------------
    # Device risk
    # --------------------------------------------------------

    if bool(
        transaction.get(
            "is_new_device",
            0,
        )
    ):
        reasons.append(
            "New device detected"
        )

    # --------------------------------------------------------
    # International transaction
    # --------------------------------------------------------

    if bool(
        transaction.get(
            "is_international",
            0,
        )
    ):
        reasons.append(
            "International transaction"
        )

    # --------------------------------------------------------
    # Merchant risk
    # --------------------------------------------------------

    merchant_risk = float(
        transaction.get(
            "merchant_risk",
            0,
        )
    )

    if merchant_risk >= 0.70:
        reasons.append(
            "High merchant risk signal"
        )

    # --------------------------------------------------------
    # IP risk
    # --------------------------------------------------------

    ip_risk = float(
        transaction.get(
            "ip_risk",
            0,
        )
    )

    if ip_risk >= 0.70:
        reasons.append(
            "High IP risk signal"
        )

    # --------------------------------------------------------
    # Network intelligence
    # --------------------------------------------------------

    network_score = float(
        signals.get(
            "network_score",
            0,
        )
    )

    if network_score >= 0.75:
        reasons.append(
            "Unusual network connectivity"
        )

    elif network_degree >= 8:
        reasons.append(
            "Dense account relationship network"
        )

    # --------------------------------------------------------
    # Fraud-ring intelligence
    # --------------------------------------------------------

    fraud_ring_score = float(
        signals.get(
            "fraud_ring_score",
            0,
        )
    )

    if fraud_ring_score >= 0.75:
        reasons.append(
            "Strong coordinated account activity detected"
        )

    elif fraud_ring_score >= 0.20:
        reasons.append(
            "Coordinated account activity detected"
        )

    # --------------------------------------------------------
    # Connected accounts
    # --------------------------------------------------------

    if connected_accounts:
        count = len(
            connected_accounts
        )

        if count == 1:
            reasons.append(
                "Account connected to 1 related account"
            )

        else:
            reasons.append(
                f"Account connected to {count} related accounts"
            )

    # --------------------------------------------------------
    # Limit explanation count
    # --------------------------------------------------------

    if not reasons:
        reasons.append(
            "No major risk indicators detected"
        )

    return reasons[:8]