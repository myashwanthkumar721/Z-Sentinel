from __future__ import annotations

import time

import pandas as pd
import streamlit as st
from streamlit_autorefresh import st_autorefresh

from src.streaming.processor import TransactionProcessor
from src.streaming.simulator import TransactionStreamSimulator


# ============================================================
# PAGE CONFIGURATION
# ============================================================

st.set_page_config(
    page_title="Z-Sentinel | Live Fraud Intelligence",
    page_icon="🛡️",
    layout="wide",
    initial_sidebar_state="expanded",
)


# ============================================================
# PAGE HEADER
# ============================================================

st.title("🛡️ Z-Sentinel")
st.caption(
    "AI-powered real-time fraud detection, risk intelligence "
    "and coordinated fraud-ring analysis."
)


# ============================================================
# SESSION STATE INITIALIZATION
# ============================================================

if "live_transactions" not in st.session_state:
    st.session_state.live_transactions = []

if "stream_running" not in st.session_state:
    st.session_state.stream_running = False

if "stream_paused" not in st.session_state:
    st.session_state.stream_paused = False

if "stream_simulator" not in st.session_state:
    st.session_state.stream_simulator = TransactionStreamSimulator()

if "stream_processor" not in st.session_state:
    st.session_state.stream_processor = TransactionProcessor()


# ============================================================
# SIDEBAR
# ============================================================

with st.sidebar:

    st.header("⚙️ Stream Controls")

    interval = st.slider(
        "Refresh Interval (seconds)",
        min_value=0.5,
        max_value=5.0,
        value=1.0,
        step=0.5,
    )

    transactions_per_cycle = st.slider(
        "Transactions per Cycle",
        min_value=1,
        max_value=10,
        value=1,
        step=1,
    )

    st.divider()

    start_col, pause_col = st.columns(2)

    with start_col:
        if st.button(
            "▶️ Start",
            use_container_width=True,
        ):
            st.session_state.stream_running = True
            st.session_state.stream_paused = False
            st.rerun()

    with pause_col:

        pause_label = (
            "▶️ Resume"
            if st.session_state.stream_paused
            else "⏸️ Pause"
        )

        if st.button(
            pause_label,
            use_container_width=True,
        ):

            if st.session_state.stream_running:
                st.session_state.stream_paused = (
                    not st.session_state.stream_paused
                )

            st.rerun()

    if st.button(
        "⏹️ Stop",
        use_container_width=True,
    ):
        st.session_state.stream_running = False
        st.session_state.stream_paused = False
        st.rerun()

    if st.button(
        "🗑️ Clear",
        use_container_width=True,
    ):
        st.session_state.live_transactions = []
        st.rerun()

    st.divider()

    if st.session_state.stream_running:

        if st.session_state.stream_paused:
            st.info("⏸️ Stream paused")
        else:
            st.success("🟢 Stream running")

    else:
        st.warning("⚪ Stream stopped")

    st.caption(
        "Transactions shown in this live dashboard are "
        "generated by the Z-Sentinel streaming simulator."
    )


# ============================================================
# NON-BLOCKING AUTO REFRESH
# ============================================================

if st.session_state.stream_running:

    st_autorefresh(
        interval=int(interval * 1000),
        key="z_sentinel_stream_refresh",
    )


# ============================================================
# STREAM PROCESSING
# ============================================================

if (
    st.session_state.stream_running
    and not st.session_state.stream_paused
):

    simulator = st.session_state.stream_simulator
    processor = st.session_state.stream_processor

    for _ in range(transactions_per_cycle):

        try:

            transaction = simulator.generate_transaction()

            result = processor.process(
                transaction,
                save_history=True,
            )

            record = {
                "transaction_id":
                    result.get(
                        "transaction_id",
                        transaction.get("transaction_id"),
                    ),

                "account_id":
                    result.get(
                        "account_id",
                        transaction.get("account_id"),
                    ),

                "amount":
                    result.get(
                        "amount",
                        transaction.get("amount", 0),
                    ),

                "ml_probability":
                    result.get(
                        "ml_probability",
                        0.0,
                    ),

                "anomaly_score":
                    result.get(
                        "anomaly_score",
                        0.0,
                    ),

                "previous_network_degree":
                    result.get(
                        "previous_network_degree",
                        0,
                    ),

                "network_degree":
                    result.get(
                        "network_degree",
                        0,
                    ),

                "network_score":
                    result.get(
                        "network_score",
                        0.0,
                    ),

                "fraud_ring_score":
                    result.get(
                        "fraud_ring_score",
                        0.0,
                    ),

                "fraud_ring_detected":
                    result.get(
                        "fraud_ring_detected",
                        False,
                    ),

                "connected_accounts":
                    result.get(
                        "connected_accounts",
                        [],
                    ),

                "risk_score":
                    result.get(
                        "risk_score",
                        0.0,
                    ),

                "decision":
                    result.get(
                        "decision",
                        "ALLOW",
                    ),

                "reasons":
                    result.get(
                        "reasons",
                        [],
                    ),

                "signals":
                    result.get(
                        "signals",
                        {},
                    ),

                "timestamp":
                    time.strftime(
                        "%H:%M:%S"
                    ),
            }

            st.session_state.live_transactions.append(
                record
            )

        except Exception as error:

            st.error(
                "Transaction processing error."
            )

            st.exception(error)


# ============================================================
